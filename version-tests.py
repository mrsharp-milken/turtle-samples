import turtle
turtle.setup(startx=10, starty=10)
tina = turtle.Turtle()
tina.shape('turtle')
tina.speed(100)
tina.width(1)
tina.color("black")
turtle.bgcolor("black")
 
def main():
    red_plus(70)    
    guitar()
    draw_whitedots()

def red_plus(size):
#    ideal size 70
    tina.color("#923041")
    tina.up()
    tina.goto(-size,-size)
    tina.down() 
    tina.lt(180)
    tina.begin_fill()
    for i in range(4):   
        tina.fd(200-size)
        tina.rt(90)
        tina.fd(2*size)
        tina.rt(90)
        tina.fd(200-size)
        tina.lt(90)
    tina.end_fill()

